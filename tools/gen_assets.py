#!/usr/bin/env python3
"""Bakes tools/plan.py + tools/furniture.py into src/plandata.js for the app."""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import plan, furniture

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# ------------------------------------------------------------------ -------
def railings():
    """glass guards around the stair void / slot."""
    r = []
    # spine hall edge of the foyer void
    r.append(dict(a=[17.40, 19.65], b=[17.40, 24.17], y=0.0))
    # landing edge over the void
    r.append(dict(a=[20.90, 19.65], b=[20.90, 21.80], y=0.0))
    # living room edge along the void + stair slot
    r.append(dict(a=[17.40, 24.17], b=[24.40, 24.17], y=0.0))
    # both sides of the stair slot through the living room
    r.append(dict(a=[20.90, 24.17], b=[20.90, 34.95], y=0.0))
    r.append(dict(a=[24.40, 24.17], b=[24.40, 34.95], y=0.0))
    # live edge at the foot of the flight
    r.append(dict(a=[20.90, 34.95], b=[24.40, 34.95], y=0.0))
    # patio + balcony perimeter guards
    r.append(dict(a=[20.17, -6.92], b=[20.17, 0.00], y=0.0))
    r.append(dict(a=[20.17, -6.92], b=[34.00, -6.92], y=0.0))
    r.append(dict(a=[34.00, -6.92], b=[34.00, 0.00], y=0.0))
    r.append(dict(a=[13.98, 41.00], b=[13.98, 55.25], y=0.0))
    r.append(dict(a=[13.98, 55.25], b=[34.00, 55.25], y=0.0))
    r.append(dict(a=[34.00, 41.00], b=[34.00, 55.25], y=0.0))
    # down the stair flight
    r.append(dict(a=[24.40, 21.80], b=[24.40, 34.95], y=0.0, stair=True))
    r.append(dict(a=[20.90, 21.80], b=[20.90, 34.95], y=0.0, stair=True))
    return r

def columns():
    c = []
    # balcony support columns + fascia beam
    for x in (15.30, 23.90, 32.80):
        c.append(dict(x=x, z=54.70, y0=0.0, y1=9.67, s=0.70))
    for x in (20.60, 33.50):
        c.append(dict(x=x, z=-6.55, y0=-10.0, y1=9.0, s=0.70))
    return c

def roofs():
    return [
        # main flat roof over the envelope
        dict(rect=[-0.60, -0.60, 34.60, 41.10], y=10.80, t=0.65, parapet=2.2),
        # patio roof
        dict(rect=[20.17, -7.00, 34.20, 0.20], y=9.00, t=0.55),
        # balcony roof (continues the living room soffit line)
        dict(rect=[13.90, 40.90, 34.20, 55.30], y=9.67, t=0.55),
    ]

def lower_level():
    """first floor below: foyer, entry, plus the stair landing walls."""
    return dict(
        y=-10.0,
        slab=[-0.60, -0.60, 34.60, 41.10],
        inner=[2.0, 14.0, 34.0, 34.0],       # foyer / garage level footprint
        door=[19.0, 0.0, 22.0, 0.4],         # front door location (north wall of foyer)
    )

# ------------------------------------------------------------------ -------
def main():
    data, holes = plan.export(os.path.join(ROOT, 'assets', 'plan.json'))
    if holes:
        print(f'WARNING: {len(holes)} uncovered cells')
    data['furniture'] = furniture.FURNITURE
    data['railings'] = railings()
    data['columns'] = columns()
    data['roofs'] = roofs()
    data['lower'] = lower_level()
    data['labels'] = [
        dict(id='living',  name='Living Room',      jump=[30.5, 31.0]),
        dict(id='kitchen', name='Kitchen',          jump=[20.5,  6.9]),
        dict(id='dining',  name='Dining',           jump=[22.0, 15.6]),
        dict(id='master',  name='Master Bedroom',   jump=[10.5, 30.0]),
        dict(id='ens',     name='Master Bathroom',  jump=[ 6.0, 20.6]),
        dict(id='wic',     name='Walk-in Closet',   jump=[ 3.5, 15.0]),
        dict(id='bed2',    name='Bedroom 2',        jump=[ 5.5,  8.2]),
        dict(id='laundry', name='Laundry',          jump=[29.0, 14.5]),
        dict(id='powder',  name='Powder Room',      jump=[13.5,  4.0]),
        dict(id='entry',   name='Stair / Entry',    jump=[23.0, 20.4]),
        dict(id='balcony', name='Covered Balcony',  jump=[20.5, 45.0]),
        dict(id='patio',   name='Covered Patio',    jump=[30.5, -3.0]),
    ]
    out = os.path.join(ROOT, 'src', 'plandata.js')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w') as fh:
        fh.write('// generated by tools/gen_assets.py - do not edit by hand\n')
        fh.write('export const PLAN = ')
        json.dump(data, fh, separators=(',', ':'))
        fh.write(';\n')
    st = data['stats']
    print(f"plandata.js written  ({os.path.getsize(out)/1024:.0f} kB)")
    print(f"  walls {len(data['walls'])}  openings {len(data['openings'])}  "
          f"rooms {len(data['rooms'])}  furniture {len(data['furniture'])}")
    print(f"  area sum {st['area_sum']:,.1f}  union {st['area_union']:,.1f}  "
          f"envelope {st['envelope']:,.1f} sq ft")

if __name__ == '__main__':
    main()
